// Captures through applyCheckers: jumped pieces leave the board, multi-jumps
// sweep the whole path, kings capture backwards where men cannot, own pieces
// are never jumpable, and crowning — simple or mid-jump — behaves per the
// rules (a man crowned by a jump stops there).

import { describe, expect, it } from 'vitest';
import { applyCheckers, IllegalMoveError, legalMovesFrom, pieceAt } from '../src/index.js';
import { at, pos } from './helpers.js';

const paths = (moves: { path: number[] }[]): number[][] =>
  moves.map((m) => m.path).sort((a, b) => String(a).localeCompare(String(b)));

describe('jumps', () => {
  it('a single jump lifts the enemy off the midpoint square', () => {
    const s = pos(
      `........
       ..d.....
       ...l....
       ........
       ........
       ........
       ........
       ....l...`,
      'dark',
    );
    const next = applyCheckers(s, { path: [at(1, 2), at(3, 4)] });
    expect(pieceAt(next, at(2, 3))).toBe('.'); // jumped
    expect(pieceAt(next, at(1, 2))).toBe('.');
    expect(pieceAt(next, at(3, 4))).toBe('d');
    expect(next.result).toBeNull();
  });

  it('a double jump takes both pieces in one move', () => {
    const s = pos(
      `........
       ..d.....
       ...l....
       ........
       .....l..
       ........
       ........
       ......l.`,
      'dark',
    );
    const next = applyCheckers(s, { path: [at(1, 2), at(3, 4), at(5, 6)] });
    expect(pieceAt(next, at(2, 3))).toBe('.');
    expect(pieceAt(next, at(4, 5))).toBe('.');
    expect(pieceAt(next, at(5, 6))).toBe('d');
    expect(next.result).toBeNull();
  });

  it('stopping a multi-jump early is illegal', () => {
    const s = pos(
      `........
       ..d.....
       ...l....
       ........
       .....l..
       ........
       ........
       ......l.`,
      'dark',
    );
    expect(() => applyCheckers(s, { path: [at(1, 2), at(3, 4)] })).toThrow(IllegalMoveError);
  });

  it('a simple move is illegal while a jump exists (mandatory capture)', () => {
    const s = pos(
      `........
       ..d.....
       ...l....
       ........
       ........
       ........
       ........
       ....l...`,
      'dark',
    );
    expect(() => applyCheckers(s, { path: [at(1, 2), at(2, 1)] })).toThrow(IllegalMoveError);
  });

  it('own pieces are never jumped', () => {
    const s = pos(
      `........
       ..d.....
       ...d....
       ........
       ........
       ........
       ........
       ........`,
      'dark',
    );
    expect(paths(legalMovesFrom(s, at(1, 2)))).toEqual(paths([{ path: [at(1, 2), at(2, 1)] }]));
    expect(() => applyCheckers(s, { path: [at(1, 2), at(3, 4)] })).toThrow(IllegalMoveError);
  });
});

describe('kings', () => {
  it('a king captures backwards; a man in the same spot cannot', () => {
    const king = pos(
      `........
       ........
       ...l....
       ..D.....
       ........
       ........
       ........
       l.......`,
      'dark',
    );
    const next = applyCheckers(king, { path: [at(3, 2), at(1, 4)] });
    expect(pieceAt(next, at(2, 3))).toBe('.');
    expect(pieceAt(next, at(1, 4))).toBe('D');

    const man = pos(
      `........
       ........
       ...l....
       ..d.....
       ........
       ........
       ........
       l.......`,
      'dark',
    );
    // No capture for a man looking backwards — only its forward steps remain.
    expect(paths(legalMovesFrom(man, at(3, 2)))).toEqual(
      paths([{ path: [at(3, 2), at(4, 1)] }, { path: [at(3, 2), at(4, 3)] }]),
    );
    expect(() => applyCheckers(man, { path: [at(3, 2), at(1, 4)] })).toThrow(IllegalMoveError);
  });

  it('a king multi-jumps through turns in direction', () => {
    const s = pos(
      `........
       ........
       ...l.l..
       ........
       ...l....
       ..D.....
       ........
       ......l.`,
      'dark',
    );
    expect(paths(legalMovesFrom(s, at(5, 2)))).toEqual(
      paths([
        { path: [at(5, 2), at(3, 4), at(1, 2)] },
        { path: [at(5, 2), at(3, 4), at(1, 6)] },
      ]),
    );
    const next = applyCheckers(s, { path: [at(5, 2), at(3, 4), at(1, 2)] });
    expect(pieceAt(next, at(4, 3))).toBe('.');
    expect(pieceAt(next, at(2, 3))).toBe('.');
    expect(pieceAt(next, at(2, 5))).toBe('l'); // the branch not taken survives
    expect(pieceAt(next, at(1, 2))).toBe('D');
  });
});

describe('crowning', () => {
  it('a man reaching the far row by a simple move is crowned', () => {
    const s = pos(
      `........
       ........
       ........
       ......l.
       ........
       ........
       .d......
       ........`,
      'dark',
    );
    const next = applyCheckers(s, { path: [at(6, 1), at(7, 0)] });
    expect(pieceAt(next, at(7, 0))).toBe('D');
    expect(next.result).toBeNull();
  });

  it('crowning ends the jump sequence even when another jump would follow', () => {
    const s = pos(
      `........
       ........
       ........
       ........
       ........
       ..d.....
       ...l.l..
       ........`,
      'dark',
    );
    // The only complete path is the single hop onto the crown row — the
    // would-be continuation over f7 needs a backward jump the new king
    // doesn't get to make this move.
    expect(paths(legalMovesFrom(s, at(5, 2)))).toEqual(
      paths([{ path: [at(5, 2), at(7, 4)] }]),
    );
    const next = applyCheckers(s, { path: [at(5, 2), at(7, 4)] });
    expect(pieceAt(next, at(7, 4))).toBe('D');
    expect(pieceAt(next, at(6, 3))).toBe('.');
    expect(pieceAt(next, at(6, 5))).toBe('l'); // survived: the sequence ended
    expect(next.result).toBeNull();
  });

  it('a light man crowns on row 1 and becomes L', () => {
    const s = pos(
      `........
       ..l.....
       ...d....
       ........
       ........
       ........
       ........
       ........`,
      'light',
    );
    const next = applyCheckers(s, { path: [at(1, 2), at(0, 1)] });
    expect(pieceAt(next, at(0, 1))).toBe('L');
  });
});
