// Custodian captures: friendly pair, hostile corners, the empty throne, the
// armed king on both ends of the pincer — and the non-captures: moving
// yourself between enemies, and flanks that run off the board.

import { describe, expect, it } from 'vitest';
import { applyCheckers, pieceAt } from '../src/index.js';
import { at, pos } from './helpers.js';

describe('custodian capture', () => {
  it('captures an enemy flanked between the mover and a friend', () => {
    const s = pos(
      `.......
       .......
       ..DA...
       ...K...
       .......
       .A.....
       .......`,
      'attackers',
    );
    const next = applyCheckers(s, { from: at(5, 1), to: at(2, 1) });
    expect(pieceAt(next, at(2, 2))).toBe('.'); // defender squeezed b3|c3|d3
    expect(pieceAt(next, at(2, 1))).toBe('A');
    expect(next.result).toBeNull();
  });

  it('captures against a corner (always hostile)', () => {
    const s = pos(
      `.D.....
       .......
       ..A....
       ...K...
       .......
       .......
       .......`,
      'attackers',
    );
    const next = applyCheckers(s, { from: at(2, 2), to: at(0, 2) });
    expect(pieceAt(next, at(0, 1))).toBe('.'); // b1 crushed against a1
  });

  it('captures against the empty throne', () => {
    const s = pos(
      `.......
       .A.....
       ...D...
       .......
       .......
       .....K.
       .......`,
      'attackers',
    );
    const next = applyCheckers(s, { from: at(1, 1), to: at(1, 3) });
    expect(pieceAt(next, at(2, 3))).toBe('.'); // d3 crushed against empty throne
  });

  it('does NOT capture against the throne while the king sits on it', () => {
    const s = pos(
      `.......
       .A.....
       ...D...
       ...K...
       .......
       .......
       .......`,
      'attackers',
    );
    const next = applyCheckers(s, { from: at(1, 1), to: at(1, 3) });
    expect(pieceAt(next, at(2, 3))).toBe('D'); // occupied throne is not hostile
  });

  it('takes multiple pieces in one move', () => {
    const s = pos(
      `.......
       .......
       AD.DA..
       .......
       .......
       ..A....
       .....K.`,
      'attackers',
    );
    const next = applyCheckers(s, { from: at(5, 2), to: at(2, 2) });
    expect(pieceAt(next, at(2, 1))).toBe('.');
    expect(pieceAt(next, at(2, 3))).toBe('.');
    expect(pieceAt(next, at(2, 0))).toBe('A'); // the anvils stand
    expect(pieceAt(next, at(2, 4))).toBe('A');
  });

  it('the king is armed: a defender captures against him (sliding over the throne)', () => {
    const s = pos(
      `.......
       .......
       .......
       .....D.
       ..A....
       ..K....
       .......`,
      'defenders',
    );
    // f4 slides across the empty throne to c4, pinning c5 against the king.
    const next = applyCheckers(s, { from: at(3, 5), to: at(3, 2) });
    expect(pieceAt(next, at(4, 2))).toBe('.');
    expect(pieceAt(next, at(5, 2))).toBe('K');
  });

  it('the king captures as the mover', () => {
    const s = pos(
      `...D...
       ...A...
       K......
       .......
       .......
       .......
       .......`,
      'defenders',
    );
    const next = applyCheckers(s, { from: at(2, 0), to: at(2, 3) });
    expect(pieceAt(next, at(1, 3))).toBe('.'); // attacker pinned king|A|D
  });

  it('the king dies two-sided like any piece → attackers win by capture', () => {
    const s = pos(
      `.......
       .......
       .AK....
       .......
       .......
       ...A...
       .......`,
      'attackers',
    );
    // d6 slides up column d, across the empty throne, to d3.
    const next = applyCheckers(s, { from: at(5, 3), to: at(2, 3) });
    expect(next.board.includes('K')).toBe(false);
    expect(next.result).toEqual({ winner: 'attackers', by: 'capture' });
  });

  it('never captures a piece that moved itself between two enemies', () => {
    const s = pos(
      `.......
       .......
       .A.A...
       .......
       .......
       ..D....
       ...K...`,
      'defenders',
    );
    const next = applyCheckers(s, { from: at(5, 2), to: at(2, 2) });
    expect(pieceAt(next, at(2, 2))).toBe('D'); // stepped into the gap, alive
    expect(pieceAt(next, at(2, 1))).toBe('A');
    expect(pieceAt(next, at(2, 3))).toBe('A');
  });

  it('no capture when the square beyond is off the board', () => {
    const s = pos(
      `....D..
       .......
       .......
       .......
       ....A..
       ...K...
       .......`,
      'attackers',
    );
    const next = applyCheckers(s, { from: at(4, 4), to: at(1, 4) });
    expect(pieceAt(next, at(0, 4))).toBe('D'); // edge alone is no anvil
  });
});
