// ported from hive/packages/app/vite.config.ts (adapted)
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import react from '@vitejs/plugin-react';
import { defineConfig, type Plugin } from 'vite';

const parlorRoot = fileURLToPath(new URL('../../../parlor', import.meta.url));
const dictGenerated = fileURLToPath(new URL('../dict/generated', import.meta.url));

// Serves the compiled DAWGs at /dict/{id}.dawg in dev and copies them into
// dist/dict at build (T3.8; @lex/dict loader BASE_PATH). Artifacts are
// generated by `pnpm --filter @lex/dict build` — never committed.
function dictAssets(): Plugin {
  let outDir = 'dist';
  return {
    name: 'lex-dict-assets',
    configResolved(config) {
      outDir = config.build.outDir;
    },
    configureServer(server) {
      server.middlewares.use('/dict', (req, res, next) => {
        const id = (req.url ?? '').replace(/^\//, '').replace(/\?.*$/, '');
        const file = join(dictGenerated, id);
        if (!id.endsWith('.dawg') || !existsSync(file)) return next();
        res.setHeader('Content-Type', 'application/octet-stream');
        res.end(readFileSync(file));
      });
    },
    closeBundle() {
      if (!existsSync(dictGenerated)) {
        this.warn('no compiled DAWGs found — run `pnpm --filter @lex/dict build` first');
        return;
      }
      const target = join(fileURLToPath(new URL('.', import.meta.url)), outDir, 'dict');
      mkdirSync(target, { recursive: true });
      for (const entry of readdirSync(dictGenerated)) {
        if (entry.endsWith('.dawg')) copyFileSync(join(dictGenerated, entry), join(target, entry));
      }
    },
  };
}

// PWA plugin (manifest + SW) attaches at T3.12/T5.1. The parlor entries are
// the §1 source-link wiring: Vite must be allowed to serve the sibling
// workspace and must transform (not prebundle) its linked TS source (§8.11).
export default defineConfig({
  build: { sourcemap: true }, // published maps: debuggability > obscurity here
  plugins: [react(), dictAssets()],
  // fs.allow: the app itself, the lex workspace root (the dev gallery imports
  // engine fixtures/test helpers), and the parlor sibling workspace.
  server: { fs: { allow: ['.', fileURLToPath(new URL('../..', import.meta.url)), parlorRoot] } },
  optimizeDeps: {
    exclude: ['@parlor/core', '@parlor/web', '@parlor/server', '@parlor/harness'],
  },
});
