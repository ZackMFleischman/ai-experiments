import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { extname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import react from '@vitejs/plugin-react';
import { defineConfig, type Plugin } from 'vite';
import { VitePWA } from 'vite-plugin-pwa';

const parlorRoot = fileURLToPath(new URL('../../../parlor', import.meta.url));
const dictGenerated = fileURLToPath(new URL('../dict/generated', import.meta.url));

// Serves the compiled DAWGs at /dict/{id}.dawg in dev and copies them into
// dist/dict at build (T3.8; @lex/dict loader BASE_PATH). Artifacts are
// generated by `pnpm --filter @lex/dict build` — never committed.
//
// Two artifact kinds live under generated/: the compiled DAWGs ({id}.dawg,
// precached by the SW) and the sharded glossary (gloss/manifest.json +
// gloss/{hash}/{n}.txt, fetched on demand when a player asks what a word means
// — DESIGN §5.5). Only these extensions are served or shipped.
const CONTENT_TYPES: Record<string, string> = {
  '.dawg': 'application/octet-stream',
  '.json': 'application/json',
  '.txt': 'text/plain; charset=utf-8',
};

/** Copy every recognized artifact under `from` into `to`, preserving structure. */
function copyTree(from: string, to: string): void {
  mkdirSync(to, { recursive: true });
  for (const entry of readdirSync(from)) {
    const source = join(from, entry);
    if (statSync(source).isDirectory()) copyTree(source, join(to, entry));
    else if (CONTENT_TYPES[extname(entry)]) copyFileSync(source, join(to, entry));
  }
}

function dictAssets(): Plugin {
  let outDir = 'dist';
  return {
    name: 'lex-dict-assets',
    configResolved(config) {
      outDir = config.build.outDir;
    },
    configureServer(server) {
      server.middlewares.use('/dict', (req, res, next) => {
        const path = (req.url ?? '').replace(/^\//, '').replace(/\?.*$/, '');
        const type = CONTENT_TYPES[extname(path)];
        const file = join(dictGenerated, path);
        // resolve() before the containment check, and compare with the
        // trailing separator so a sibling `generated-x/` can't prefix-match:
        // a '..' in the request must never escape generated/ (dev server, but
        // the habit is cheap).
        const root = resolve(dictGenerated) + sep;
        if (!type || !resolve(file).startsWith(root) || !existsSync(file)) return next();
        res.setHeader('Content-Type', type);
        res.end(readFileSync(file));
      });
    },
    closeBundle() {
      if (!existsSync(dictGenerated)) {
        this.warn('no compiled dictionaries found — run `pnpm --filter @lex/dict build` first');
        return;
      }
      const target = join(fileURLToPath(new URL('.', import.meta.url)), outDir, 'dict');
      // The DAWGs sit at the top level; the glossary is a tree (gloss/<hash>/…),
      // so copy the whole generated/ subtree and let CONTENT_TYPES decide what
      // belongs in the build — one rule for both artifact kinds.
      copyTree(dictGenerated, target);
      if (!existsSync(join(target, 'gloss'))) {
        this.warn('no glossary artifact found — definitions will fall back to the link-out');
      }
    },
  };
}

// PWA plugin (manifest + SW) attaches at T3.12/T5.1. The parlor entries are
// the §1 source-link wiring: Vite must be allowed to serve the sibling
// workspace and must transform (not prebundle) its linked TS source (§8.11).
